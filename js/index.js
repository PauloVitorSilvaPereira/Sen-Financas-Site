$(document).ready(function () {
    $('.InfoImgs').mouseover(function () {
      $(this).css('width', 364)
    })
    $('.InfoImgs').mouseout(function () {
      $(this).css('width', 356)
    })
    $('.InfoImgs').mouseover(function () {
      $(this).css('height', 208)
    })
    $('.InfoImgs').mouseout(function () {
      $(this).css('height', 200)
    })
})